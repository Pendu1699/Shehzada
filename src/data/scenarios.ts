import type { Festival } from '../engine/calendar';

export interface ScenarioArmy {
  owner: string;
  region: string;
  units: [string, number][];
  leader?: string;
  name?: string;
}

export interface ScenarioDef {
  id: string;
  title: string;
  gurmukhi?: string;
  year: number;
  festival: Festival;
  blurb: string;
  /** Which factions the player may choose. */
  playable: string[];
  recommended: string;
  owners: Record<string, string>;
  /** Regions paying rakhi to a misl at start. */
  rakhi?: Record<string, string>;
  armies: ScenarioArmy[];
  treasury: Record<string, number>;
  piri: Record<string, number>;
  /** Factions not yet on the map (they arrive by event). */
  absent?: string[];
  /** Extra flags per faction. */
  flags?: Record<string, Record<string, number | boolean | string>>;
  /** Initial wars as [a, b] pairs; everything else starts at peace. */
  wars: [string, string][];
  /** Alliances. */
  alliances?: [string, string][];
  /** Factions recognised as the Sarkar-i-Khalsa at start. */
  sarkar?: string;
  /** The Long Struggle: a political game after the annexation. */
  mode?: 'struggle';
}

